BINS = [1, 4, 7, 10, 13, 16, 20, 25, 30, 40, 55, 80, 120, 10 ** 6]


def binned(by_node, min_n=5):
    """(x, mean, half-width of a 95% interval) per node-count bin from per-node (n, mean, sd)."""
    out = []
    for lo, hi in zip(BINS[:-1], BINS[1:]):
        rows = [(int(k), *v) for k, v in by_node.items() if lo <= int(k) < hi and v[1] is not None]
        n = sum(r[1] for r in rows)
        if n < min_n:
            continue
        mean = sum(r[1] * r[2] for r in rows) / n
        ss = sum((r[1] - 1) * r[3] ** 2 + r[1] * (r[2] - mean) ** 2 for r in rows)
        sd = np.sqrt(ss / max(n - 1, 1))
        x = sum(r[1] * r[0] for r in rows) / n
        out.append((x, mean, 1.96 * sd / np.sqrt(n)))
    return np.array(out) if out else np.zeros((0, 3))


