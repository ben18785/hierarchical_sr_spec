    # -- corpus
    def corpus_table(self):
        S = self.corpus["sources"]
        body = []
        for role, title in (("training", "Training sources"), ("holdout", "Hold-out sources (never trained on)")):
            names = sorted([n for n in S if S[n]["role"] == role], key=lambda n: -S[n]["pairs"])
            body.append(("GROUP", title))
            for n in names:
                s, m = S[n], self.src.get(n, {})
                body.append([self.label(n), intc(s["models"]), intc(s["pairs"]), intc(s["distinct"]),
                             esc(m.get("licence", "")), esc(m.get("route", ""))])
            forms = set().union(*(S[n]["forms"] for n in names))
            body.append(["All " + ("training" if role == "training" else "hold-out"),
                         intc(sum(S[n]["models"] for n in names)), intc(sum(S[n]["pairs"] for n in names)),
                         intc(len(forms)), "", ""])
            body.append("MID")
        body.pop()
        tabular(self.path("corpus"), "lrrrll",
                ["Source & Models & Model--form pairs & Distinct forms & Licence & Extraction"], body,
                ["Distinct forms: generalised keys; totals count each form once."])

