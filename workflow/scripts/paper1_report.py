def uniform_symbols_finite():
    """P(finite) of the prior that draws every node's symbol uniformly from
    hsr.treecode.V: the smallest root of q = sum_s q^arity(s) / |V|, and the
    branching mean sum_s arity(s) / |V| (improper when the mean exceeds 1)."""
    ar = [tc.ARITY[s] for s in tc.V]
    q = 0.0
    for _ in range(100000):
        qn = float(np.mean([q ** a for a in ar]))
        if abs(qn - q) < 1e-15:
            break
        q = qn
    return q, float(np.mean(ar))


