# ------------------------------------------------------------------ helpers

def load(path):
    with open(path) as fh:
        return json.load(fh)


def num(x, nd=2):
    """A number for a table cell; negative numbers in math mode; '--' if missing."""
    if x is None or (isinstance(x, float) and not np.isfinite(x)):
        return "--"
    s = f"{x:.{nd}f}"
    if s.startswith("-"):
        return f"${s}$"
    return s


def intc(x):
    return "--" if x is None else f"{int(x):,}".replace(",", "{,}")


def sci(x):
    """Small positive number as a power of ten."""
    if x is None:
        return "--"
    if x <= 0:
        return "$<10^{-15}$"
    e = int(np.floor(np.log10(x)))
    m = x / 10 ** e
    return f"${m:.1f}\\times 10^{{{e}}}$"


def esc(s):
    return s.replace("\\", "\\textbackslash{}").replace("_", "\\_").replace("&", "\\&").replace("%", "\\%")


def pname(p):
    """Display name of a prior or blend."""
    if p in ("flat", "uniform symbols", "all tree priors"):
        return p
    if " + " in p:
        return " + ".join(pname(q) for q in p.split(" + "))
    return f"\\texttt{{{esc(p)}}}"


def tabular(path, colspec, head, body, notes=None):
    """Write a booktabs tabular. head: list of header lines (without \\\\);
    body: list of rows (lists of cells) or the string "MID" for a midrule, or
    ("GROUP", text) for a full-width group label."""
    ncol = len([c for c in colspec if c.isalpha()])
    L = [HEADER.rstrip("\n")]
    if notes:
        L += [f"% {n}" for n in notes]
    L += [f"\\begin{{tabular}}{{{colspec}}}", "\\toprule"]
    for h in head:
        L.append(h if h.startswith("\\cmidrule") else h + " \\\\")
    L.append("\\midrule")
    for r in body:
        if r == "MID":
            L.append("\\midrule")
        elif isinstance(r, tuple) and r[0] == "GROUP":
            L.append(f"\\multicolumn{{{ncol}}}{{l}}{{\\emph{{{r[1]}}}}} \\\\")
        else:
            if len(r) != ncol:
                raise ValueError(f"{path}: row has {len(r)} cells, expected {ncol}")
            L.append(" & ".join(r) + " \\\\")
    L += ["\\bottomrule", "\\end{tabular}"]
    with open(path, "w") as fh:
        fh.write("\n".join(L) + "\n")


def groups_head(groups, sub, first=("",)):
    """Two header lines: group names spanning len(sub) columns each, then sub-column names."""
    n0 = len(first)
    cells, rules = [], []
    for i, g in enumerate(groups):
        cells.append(f"\\multicolumn{{{len(sub)}}}{{c}}{{{g}}}")
        a = n0 + 1 + i * len(sub)
        rules.append(f"\\cmidrule(lr){{{a}-{a + len(sub) - 1}}}")
    return [" & ".join([""] * n0 + cells), " ".join(rules), " & ".join(list(first) + list(sub) * len(groups))]


def tree_priors(stats, extra=()):
    """Tree priors present in ``stats``, in display order."""
    out = [p for p in TREE_ORDER if p in stats]
    out += [p for p in stats if stats[p].get("family") == "tree" and p not in out and p not in extra]
    return out


def all_priors(stats):
    tree = tree_priors(stats, extra=("uniform symbols",))
    pcfg = [p for p in stats if stats[p].get("family") == "pcfg"]
    rest = [p for p in stats if p not in tree and p not in pcfg]
    return tree, pcfg, rest


def mean_over(vals):
    v = [x for x in vals if x is not None]
    return float(np.mean(v)) if v else None


