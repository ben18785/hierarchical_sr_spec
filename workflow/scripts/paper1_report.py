        ax.fill_between(sw, lo, hi, color=BLUE, alpha=0.2, lw=0, label="10-90% of fits")
        ax.plot(sw, med, color=BLUE, lw=1.5, label="median")
        ax.set_title(f"{v} ({A.shape[0]} fits)")
        ax.set_xlabel("Sweep")
        ax.set_ylim(0, max(ax.get_ylim()[1], 1.05 * hi.max()))
